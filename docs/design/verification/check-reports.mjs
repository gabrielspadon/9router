#!/usr/bin/env node
// Compares the before and after audits and writes the reports the brief asks
// for: accessibility, console, network, contrast, keyboard, colour-vision and
// reflow, each with a baseline number and a current number.
//
// The gate is that nothing regressed. An improvement is welcome but not
// required; a regression fails.
import { readFileSync, existsSync, writeFileSync, mkdirSync } from "node:fs";
const consoleNetworkOnly = process.argv.includes("--console-network");
const P = (m) => `docs/design/evidence/raw/${m}.json`;
for (const m of ["before", "after"]) if (!existsSync(P(m))) { console.log(`missing ${P(m)}`); process.exit(1); }
const before = JSON.parse(readFileSync(P("before"), "utf8"));
const after = JSON.parse(readFileSync(P("after"), "utf8"));

const sum = (d, f) => Object.values(d.routes).reduce((a, r) => a + f(r), 0);
const metrics = [
  ["console errors", (r) => (r.consoleErrors || []).length],
  ["failed or 5xx requests", (r) => (r.failedRequests || []).length],
  ["contrast failures", (r) => (r.contrast || []).length],
  ["unnamed icon controls", (r) => (r.names?.unnamed || []).length],
  ["focus ring failures", (r) => (r.focus?.bad || []).length],
  ["hue-only status indicators", (r) => (r.hueOnly || []).length],
  ["views overflowing at 200 percent zoom", (r) => (r.reflow?.overflow ? 1 : 0)],
  ["navigation failures", (r) => (r.navError ? 1 : 0)],
];

const rows = metrics.map(([name, f]) => {
  const b = sum(before, f), a = sum(after, f);
  return { name, before: b, after: a, delta: a - b, regressed: a > b };
});

// Keyboard traversal is recorded per route rather than summed.
const tabBefore = Object.values(before.routes).filter((r) => r.tabOrder).length;
const tabAfter = Object.values(after.routes).filter((r) => r.tabOrder).length;
const unnamedStopsBefore = Object.values(before.routes).reduce((a, r) => a + (r.tabOrder?.unnamed || 0), 0);
const unnamedStopsAfter = Object.values(after.routes).reduce((a, r) => a + (r.tabOrder?.unnamed || 0), 0);
rows.push({ name: "unnamed keyboard stops", before: unnamedStopsBefore, after: unnamedStopsAfter,
  delta: unnamedStopsAfter - unnamedStopsBefore, regressed: unnamedStopsAfter > unnamedStopsBefore });

const w = Math.max(...rows.map((r) => r.name.length));
console.log(`views: ${Object.keys(before.routes).length} before, ${Object.keys(after.routes).length} after`);
console.log(`keyboard traversal recorded on ${tabBefore} routes before, ${tabAfter} after`);
for (const r of rows)
  console.log(`  ${r.name.padEnd(w)}  ${String(r.before).padStart(5)} -> ${String(r.after).padStart(5)}  ${r.regressed ? "REGRESSED" : r.delta < 0 ? "improved" : "same"}`);

mkdirSync("docs/design/evidence", { recursive: true });
const md = [
  "# Audit report, baseline against current",
  "",
  "Generated by `docs/design/verification/check-reports.mjs` from the before and",
  "after captures of `docs/design/verification/audit2.mjs`. Baseline is the branch",
  "tip before the redesign began; current is the same tree after it.",
  "",
  `Coverage: ${Object.keys(before.routes).length} views before and ${Object.keys(after.routes).length} after, across every audited route, both themes, three viewports plus a 200 percent zoom pass.`,
  "",
  "| Measure | Baseline | Current | Result |",
  "|---|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.before} | ${r.after} | ${r.regressed ? "regressed" : r.delta < 0 ? "improved" : "unchanged"} |`),
  "",
  "A regression on any row fails the gate. An improvement is welcome but is not",
  "required for the gate to pass.",
  "",
].join("\n");
writeFileSync("docs/design/evidence/audit-report.md", md);

const regressed = rows.filter((r) => r.regressed);
if (consoleNetworkOnly) {
  // The contract is no regression, not zero. The application already logs
  // resource-load failures on some routes; introducing none is what this work
  // is answerable for, so compare the message sets rather than the totals.
  const msgs = (d) => {
    const m = new Map();
    for (const r of Object.values(d.routes)) {
      for (const e of r.consoleErrors || []) m.set(e.slice(0, 90), (m.get(e.slice(0, 90)) || 0) + 1);
      for (const e of r.failedRequests || []) m.set("net:" + e.slice(0, 90), (m.get("net:" + e.slice(0, 90)) || 0) + 1);
    }
    return m;
  };
  const B = msgs(before), A = msgs(after);
  const introduced = [...A.entries()].filter(([k, n]) => n > (B.get(k) || 0));
  console.log(`distinct console and network messages: ${B.size} before, ${A.size} after`);
  for (const [k, n] of A) console.log(`  ${String(n).padStart(3)} x ${k}`);
  if (introduced.length) {
    console.log(`INTRODUCED=${introduced.length}`);
    introduced.forEach(([k, n]) => console.log(`  ${(B.get(k) || 0)} -> ${n}  ${k}`));
    process.exit(1);
  }
  console.log("CONSOLE NETWORK OK");
  process.exit(0);
}
if (regressed.length) { console.log(`REGRESSED=${regressed.length}`); process.exit(1); }
console.log("REPORTS OK");
