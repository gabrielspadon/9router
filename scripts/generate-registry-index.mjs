import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const defaultRegistryDirectory = resolve(scriptDirectory, "../open-sse/providers/registry");

const DISABLED_ENTRIES = new Map([
  ["devin-cli.js", "spawns a local agent with shell and filesystem access"],
  ["trae.js", "no tool calling support"],
  ["windsurf.js", "no tool calling support"],
]);

function parseArguments(argumentsList) {
  let registryDirectory = defaultRegistryDirectory;
  let check = false;

  for (let index = 0; index < argumentsList.length; index += 1) {
    const argument = argumentsList[index];
    if (argument === "--check") {
      check = true;
      continue;
    }
    if (argument === "--registry-dir") {
      const directory = argumentsList[index + 1];
      if (!directory) throw new Error("--registry-dir requires a path");
      registryDirectory = resolve(directory);
      index += 1;
      continue;
    }
    throw new Error(`Unknown argument: ${argument}`);
  }

  return { check, registryDirectory };
}

function getRegistryFiles(registryDirectory) {
  return readdirSync(registryDirectory)
    .filter((filename) => filename.endsWith(".js") && filename !== "index.js")
    .sort();
}

function renderRegistryIndex(filenames) {
  const entries = filenames.map((filename, index) => ({
    disabledReason: DISABLED_ENTRIES.get(filename),
    filename,
    symbol: `p${index}`,
  }));
  const lines = ["// Auto-generated by scripts/generate-registry-index.mjs. Do not edit by hand."];

  for (const { disabledReason, filename, symbol } of entries) {
    if (disabledReason) lines.push(`// Disabled: ${disabledReason}`);
    lines.push(`${disabledReason ? "// " : ""}import ${symbol} from \"./${filename}\";`);
  }

  lines.push("", "export default [");
  for (const { disabledReason, symbol } of entries) {
    if (disabledReason) lines.push(`  // ${symbol} remains disabled`);
    else lines.push(`  ${symbol},`);
  }
  lines.push("];", "");

  return lines.join("\n");
}

function main() {
  const { check, registryDirectory } = parseArguments(process.argv.slice(2));
  const indexPath = join(registryDirectory, "index.js");
  const generated = renderRegistryIndex(getRegistryFiles(registryDirectory));
  const current = existsSync(indexPath) ? readFileSync(indexPath, "utf8") : null;

  if (check) {
    if (current !== generated) {
      console.error("Provider registry index is out of date. Run: node scripts/generate-registry-index.mjs");
      process.exitCode = 1;
    }
    return;
  }

  if (current !== generated) writeFileSync(indexPath, generated, "utf8");
}

main();
